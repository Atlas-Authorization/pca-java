package net.atlasauth.pca;

import static org.junit.jupiter.api.Assertions.*;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.function.Function;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

/**
 * Mutation kills for IntentAcc.java (rule 15: accumulator / monitor declarations, selection and values, pre-states,
 * reservation receipts, sequencer key sets, receipt verification against the sequenced holder). Differential against
 * the TS reference packages/pca/src/intent-acc.ts: test-data/k042-intentacc.json is generated by
 * tools/pca-audit/java-mutate/k042-intentacc-oracle.mjs and every case asserts the EXACT reason / verdict / value.
 */
public class K042IntentAccOracleTest {
    static List<Map<String, Object>> CASES;

    @BeforeAll
    @SuppressWarnings("unchecked")
    static void load() throws Exception {
        String text = new String(Files.readAllBytes(Path.of("test-data/k042-intentacc.json")), StandardCharsets.UTF_8);
        CASES = new ArrayList<>();
        for (Object o : (List<Object>) Json.parseLenient(text)) CASES.add((Map<String, Object>) o);
        assertTrue(CASES.size() > 1500, "corpus loaded");
    }

    @SuppressWarnings("unchecked")
    static List<Object> args(Map<String, Object> c) { return (List<Object>) c.get("args"); }
    static Map<String, Object> m(Object o) { return IntentJs.obj(o); }
    static String s(Object o) { return (String) o; }
    static double d(Object o) { return IntentJs.num(o); }

    /** Runs every case of {@code fn}; each must equal the TS output (compared as canonical JSON). */
    static void run(String fn, Function<List<Object>, Object> f) {
        List<String> bad = new ArrayList<>();
        int n = 0;
        for (Map<String, Object> c : CASES) {
            if (!fn.equals(c.get("fn"))) continue;
            n++;
            Object got;
            try {
                got = f.apply(args(c));
            } catch (RuntimeException e) {
                got = "THREW " + e;
            }
            String want = Json.canonicalize(c.get("out"));
            String g = Json.canonicalize(toJson(got));
            if (!want.equals(g)) bad.add(c.get("name") + "\n    want " + want + "\n    got  " + g);
        }
        assertTrue(n > 0, "no cases for " + fn);
        assertTrue(bad.isEmpty(), bad.size() + "/" + n + " " + fn + " cases differ from the TS reference:\n  " + String.join("\n  ", bad.subList(0, Math.min(bad.size(), 40))));
    }

    static Object toJson(Object o) {
        if (o instanceof Long || o instanceof Integer) return new Json.Num(o.toString());
        if (o instanceof IntentAcc.AccValue) {
            IntentAcc.AccValue v = (IntentAcc.AccValue) o;
            Map<String, Object> r = new java.util.LinkedHashMap<>();
            if (v.reason != null) {
                r.put("ok", false);
                r.put("reason", v.reason);
                // a refusal carries no value and no key
                if (v.val != 0 || v.key != null) r.put("leaked", v.val + "/" + v.key);
            } else {
                r.put("ok", true);
                r.put("val", new Json.Num(Long.toString(v.val)));
                r.put("key", v.key);
            }
            return r;
        }
        return o;
    }

    @Test void accumulatorDeclError() { run("accumulatorDeclError", a -> IntentAcc.accumulatorDeclError(a.get(0))); }

    @Test void monitorDeclError() { run("monitorDeclError", a -> IntentAcc.monitorDeclError(a.get(0))); }

    @Test void monitorStates() { run("monitorStates", a -> IntentAcc.monitorStates(m(a.get(0)))); }

    @Test void trackedKeySetError() { run("trackedKeySetError", a -> IntentAcc.trackedKeySetError(a.get(0))); }

    @Test void preState() {
        run("preStateError", a -> IntentAcc.preStateError(a.get(0), a.get(1)));
        run("preValue", a -> IntentAcc.preValue(a.get(0), m(a.get(1))));
        run("combineAcc", a -> {
            Object key = IntentJs.get(a.get(2), "key");
            return IntentAcc.combineAcc(a.get(0), m(a.get(1)), new IntentAcc.AccValue(null, IntentJs.lng(IntentJs.get(a.get(2), "val")), (String) key));
        });
    }

    @Test void selectionAndValues() {
        run("accSelects", a -> IntentAcc.accSelects(m(a.get(0)), s(a.get(1)), a.get(2)));
        run("accValueOf", a -> IntentAcc.accValueOf(m(a.get(0)), s(a.get(1)), m(a.get(2)), a.get(3)));
    }

    @Test void receiptArithmeticOk() { run("receiptArithmeticOk", a -> IntentAcc.receiptArithmeticOk(a.get(0), m(a.get(1)), IntentJs.lng(a.get(2)))); }

    @Test void pcactnReservationDigest() { run("pcactnReservationDigest", a -> IntentAcc.pcactnReservationDigest(m(a.get(0)))); }

    @Test void receiptShapeError() { run("receiptShapeError", a -> IntentAcc.receiptShapeError(a.get(0))); }

    @Test void keySetShapeError() { run("keySetShapeError", a -> IntentAcc.keySetShapeError(a.get(0))); }

    @Test void verifyKeySet() { run("verifyKeySet", a -> IntentAcc.verifyKeySet(a.get(0), s(a.get(1)), a.get(2), (Boolean) a.get(3))); }

    @Test void verifyReceiptSignature() {
        run("verifyReceiptSignature", a -> a.get(0) instanceof Map ? IntentAcc.verifyReceiptSignature(m(a.get(0)), s(a.get(1)), a.get(2) == null ? null : m(a.get(2))) : false);
    }

    @Test void verifyReceiptAgainstHolder() {
        run("verifyReceiptAgainstHolder", a -> IntentAcc.verifyReceiptAgainstHolder(m(a.get(0)), m(a.get(1)), a.get(2), d(a.get(3)), d(a.get(4)), d(a.get(5)), a.get(6)));
    }

    static List<Object> caseArgs(String name) {
        for (Map<String, Object> c : CASES) if (name.equals(c.get("name"))) return args(c);
        throw new AssertionError("no case " + name);
    }

    @Test void monitorStatesOfAnUnknownKindIsEmpty() {
        assertEquals(List.of(), IntentAcc.monitorStates(m(Json.parseLenient("{\"kind\":\"other\"}"))));
        assertEquals(List.of(), IntentAcc.monitorStates(m(Json.parseLenient("{}"))));
    }

    @Test void verifyKeySetPinsOnlyWhenTheRootPqKeyIsPresent() {
        List<Object> pq = caseArgs("verifyKeySet/pq-pinned");
        assertTrue(IntentAcc.verifyKeySet(pq.get(0), s(pq.get(1)), pq.get(2), true));
        // the same key, but declared absent: no pin, so a PQ set never verifies
        assertFalse(IntentAcc.verifyKeySet(pq.get(0), s(pq.get(1)), pq.get(2), false));
        // a root that is not a string fails closed (never throws, never verifies)
        List<Object> ok = caseArgs("verifyKeySet/ok");
        assertTrue(IntentAcc.verifyKeySet(ok.get(0), s(ok.get(1)), null, false));
        assertFalse(IntentAcc.verifyKeySet(ok.get(0), null, null, false));
    }
}
