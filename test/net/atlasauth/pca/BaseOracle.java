package net.atlasauth.pca;

import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.lang.ref.SoftReference;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.zip.GZIPInputStream;

/**
 * Loads a base oracle (test-data/base-&lt;module&gt;.json.gz: a header line, then one case per line) line by line, optionally only
 * the cases of one fn, into a soft cache. The oracles are up to 170 MB of JSON: reading a whole file into one string, or
 * keeping every module's cases strongly reachable, ran the surefire fork (2 GB) out of heap.
 */
final class BaseOracle {
    private BaseOracle() {}

    /** Corpora whose tests resolve their own {"$seed": label} placeholders (the label is the argument, not a key to materialize). */
    private static final java.util.Set<String> BESPOKE_SEEDS = java.util.Set.of("ref-wallet", "ref-actions-signbuiltins-py");

    /** Replaces every {"$seed": label[, "es256": true]} object by base64url(SHA-256("atlas-pca-conformance/" + label)), top bit of byte 0 cleared for es256. */
    @SuppressWarnings("unchecked")
    static Object resolveSeeds(Object v) {
        if (v instanceof List) {
            List<Object> l = (List<Object>) v;
            for (int i = 0; i < l.size(); i++) l.set(i, resolveSeeds(l.get(i)));
            return l;
        }
        if (!(v instanceof Map)) return v;
        Map<String, Object> m = (Map<String, Object>) v;
        if (m.size() == 1 && m.get("$utf16") instanceof List) { // {"$utf16": [code units]}: a string holding a lone surrogate
            StringBuilder sb = new StringBuilder();
            for (Object u : (List<Object>) m.get("$utf16")) sb.append((char) ((Number) u).intValue());
            return sb.toString();
        }
        if (m.get("$seed") instanceof String && java.util.Set.of("$seed", "es256", "ec", "ed448").containsAll(m.keySet())) {
            try {
                java.security.MessageDigest md = java.security.MessageDigest.getInstance("SHA-256");
                String p = "atlas-pca-conformance/" + m.get("$seed");
                byte[] h1 = md.digest(p.getBytes(StandardCharsets.UTF_8));
                byte[] h2 = md.digest((p + "/2").getBytes(StandardCharsets.UTF_8));
                byte[] h3 = md.digest((p + "/3").getBytes(StandardCharsets.UTF_8));
                byte[] all = new byte[96];
                System.arraycopy(h1, 0, all, 0, 32); System.arraycopy(h2, 0, all, 32, 32); System.arraycopy(h3, 0, all, 64, 32);
                byte[] raw = h1;
                if ("P-384".equals(m.get("ec"))) { raw = java.util.Arrays.copyOf(all, 48); raw[0] &= 0x7F; }
                else if ("P-521".equals(m.get("ec"))) { raw = java.util.Arrays.copyOf(all, 66); raw[0] &= 0x01; }
                else if (Boolean.TRUE.equals(m.get("ed448"))) { raw = java.util.Arrays.copyOf(all, 57); System.arraycopy(h2, 0, raw, 32, 25); }
                else if (Boolean.TRUE.equals(m.get("es256"))) raw[0] &= 0x7F;
                return java.util.Base64.getUrlEncoder().withoutPadding().encodeToString(raw);
            } catch (java.security.NoSuchAlgorithmException e) { throw new IllegalStateException(e); }
        }
        for (Map.Entry<String, Object> e : m.entrySet()) e.setValue(resolveSeeds(e.getValue()));
        return m;
    }

    static final String RSA = "ref-dpop-rsa";

    /** ref-dpop-rsa is generated by CI (never committed): PCA_DPOP_RSA_CORPUS, else test-data/. */
    static Path corpusPath(String module) {
        String env = System.getenv("PCA_DPOP_RSA_CORPUS");
        return RSA.equals(module) && env != null && !env.isEmpty() ? Path.of(env) : Path.of("test-data/" + module + ".json.gz");
    }

    /** Corpora whose private-key cases are generated by CI (never committed) into <name>-gen.json.gz next to the main corpus (PCA_SECRET_CORPUS_DIR overrides the directory). */
    static final java.util.Set<String> GEN = java.util.Set.of("ref-oprf", "ref-core-frost-java", "ref-mpc-ot", "ref-attest-eat", "ref-abe", "ref-frost-dkg");

    static Path genPath(String module) {
        String env = System.getenv("PCA_SECRET_CORPUS_DIR");
        Path dir = env != null && !env.isEmpty() ? Path.of(env) : corpusPath(module).toAbsolutePath().getParent();
        return dir.resolve(module + "-gen.json.gz");
    }

    /** The -gen corpus must exist when CI is "true"/"1" (generate with gen-secret-corpus.sh), else the calling test is skipped. */
    static void requireGen(String module) {
        Path p = genPath(module);
        String ci = System.getenv("CI");
        boolean inCi = "true".equals(ci) || "1".equals(ci);
        String msg = "secret oracle corpus missing: " + p + " (generate with gen-secret-corpus.sh or set PCA_SECRET_CORPUS_DIR)";
        if (inCi) org.junit.jupiter.api.Assertions.assertTrue(Files.exists(p), msg);
        else org.junit.jupiter.api.Assumptions.assumeTrue(Files.exists(p), msg);
    }

    /** The generator clock (epoch ms) of corpora committed before the header carried "clockMs". */
    static final double FALLBACK_CLOCK_MS = 1_800_000_000_000d;

    /** The frozen clock a corpus header line (everything up to the opening bracket of "cases") records as "clockMs", else {@link #FALLBACK_CLOCK_MS}. */
    static double clockOfHeader(String header) {
        if (header == null || !header.endsWith("[")) return FALLBACK_CLOCK_MS;
        Object v = ((Map<?, ?>) Json.parseLenient(header.substring(0, header.length() - 1) + "]}")).get("clockMs");
        Double d = v instanceof Json.Num ? Double.valueOf(((Json.Num) v).raw) : v instanceof Number ? Double.valueOf(((Number) v).doubleValue()) : null;
        return d != null && !d.isNaN() && !d.isInfinite() ? d : FALLBACK_CLOCK_MS;
    }

    /** The one clock accessor of the replays: the frozen clock of the corpus {@code module} (e.g. "ref-revoke"). */
    static double clockMs(String module) {
        try (BufferedReader in = new BufferedReader(new InputStreamReader(new GZIPInputStream(Files.newInputStream(corpusPath(module))), StandardCharsets.UTF_8))) {
            return clockOfHeader(in.readLine());
        } catch (java.io.IOException e) {
            throw new java.io.UncheckedIOException(e);
        }
    }

    private static final Map<String, SoftReference<List<Map<String, Object>>>> CACHE = new HashMap<>();

    /** Every case of the module (normalized like the k042 tests). */
    static List<Map<String, Object>> all(String module) throws Exception { return load(module, null); }

    /** The cases of one fn (empty when there are none). */
    static List<Map<String, Object>> of(String module, String fn) throws Exception { return load(module, fn); }

    @SuppressWarnings("unchecked")
    private static synchronized List<Map<String, Object>> load(String module, String fn) throws Exception {
        String key = module + "\u0000" + fn;
        SoftReference<List<Map<String, Object>>> r = CACHE.get(key);
        List<Map<String, Object>> out = r == null ? null : r.get();
        if (out != null) return out;
        out = new ArrayList<>();
        String head = fn == null ? "{\"fn\":" : "{\"fn\":" + Json.canonicalize(fn) + ",";
        readInto(out, corpusPath(module), module, head);
        if (GEN.contains(module) && Files.exists(genPath(module))) readInto(out, genPath(module), module, head);
        if (out.isEmpty() && fn == null) throw new IllegalStateException("no cases in " + module);
        CACHE.put(key, new SoftReference<>(out));
        return out;
    }

    @SuppressWarnings("unchecked")
    private static void readInto(List<Map<String, Object>> out, Path file, String module, String head) throws Exception {
        try (BufferedReader in = new BufferedReader(new InputStreamReader(
                new GZIPInputStream(Files.newInputStream(file)), StandardCharsets.UTF_8))) {
            for (String line; (line = in.readLine()) != null; ) {
                if (!line.startsWith(head)) continue;
                if (line.endsWith(",")) line = line.substring(0, line.length() - 1);
                Map<String, Object> c = (Map<String, Object>) (BESPOKE_SEEDS.contains(module) ? IntentJs.normalize(Json.parseLenient(line)) : resolveSeeds(IntentJs.normalize(Json.parseLenient(line))));
                if (c.get("args") instanceof Map) c.put("args", new ArrayList<Object>(List.of(c.get("args")))); // a few generators record their one argument object bare
                out.add(c);
            }
        }
    }
}
