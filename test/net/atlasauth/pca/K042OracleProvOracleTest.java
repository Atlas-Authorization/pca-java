package net.atlasauth.pca;

import static org.junit.jupiter.api.Assertions.*;

import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.function.Function;
import java.util.zip.GZIPInputStream;
import org.junit.jupiter.api.Test;

/**
 * 0.4.2 mutation kills for OracleFacts.java (rule 16: facts, relational dimensions, offer sets) and ParamProvenance.java
 * (rule 17: provenance, label receipts, flows, read purpose): a differential test against the TS reference
 * (oracle-facts.ts, offer-set.ts, label-receipts.ts, param-provenance.ts). The expected results are generated by
 * tools/pca-audit/java-mutate/k042-oracleprov-oracle.mjs into test-data/k042-oracleprov.json.gz. Every case compares the
 * FULL result: the exact validator reason, the exact refusal reason, world (with member order), single_source, outcome,
 * friction, labels, classes, env, the read-purpose lists, the activity verdict, ratio_ppm and the flow-rule choice.
 */
public class K042OracleProvOracleTest {
    static final String GOLDEN = "test-data/k042-oracleprov.json.gz";

    /**
     * Where this verifier's reason differs from the reference BY DESIGN: a non-object input is caught as an internal error
     * in Java (the exception's simple class name), where TypeScript checks the input type first. Pinned exactly.
     */
    static final Map<String, String> JAVA_REASON = Map.of(
        "world/k042-input-null", "facts: evaluation error (fail closed): NullPointerException",
        "world/k042-input-array", "facts: evaluation error (fail closed): ClassCastException",
        "prov/k042-input-null", "provenance: evaluation error (fail closed): NullPointerException",
        "prov/k042-input-array", "provenance: evaluation error (fail closed): ClassCastException");
        // (prov/k042-aud-missing is no longer a divergence: a missing aud is refused with the TS flow reason, 'undefined')

    static final Map<String, Function<Object, String>> VALIDATORS = Map.of(
        "validateFactWire", OracleFacts::validateFactWire,
        "validateWorldPolicy", OracleFacts::validateWorldPolicy,
        "validateOfferPolicy", OracleFacts::validateOfferPolicy,
        "validateOfferSetWire", OracleFacts::validateOfferSetWire,
        "validateLabelsWire", ParamProvenance::validateLabelsWire,
        "validateFlowRules", ParamProvenance::validateFlowRules,
        "validateProvenancePolicy", ParamProvenance::validateProvenancePolicy,
        "validateProvWire", ParamProvenance::validateProvWire);

    static List<Object> cases() throws Exception {
        try (InputStream in = new GZIPInputStream(Files.newInputStream(Path.of(GOLDEN)))) {
            Object doc = IntentJs.normalize(Json.parseLenient(new String(in.readAllBytes(), StandardCharsets.UTF_8)));
            return IntentJs.arr(IntentJs.get(doc, "cases"));
        }
    }

    /** JSON text keeping member ORDER (so a reordered world / labels map is a difference), numbers by value. */
    static String ser(Object v) {
        if (v == null) return "null";
        if (v instanceof String) return Json.canonicalize(v);
        if (v instanceof Boolean) return v.toString();
        if (v instanceof Map) {
            StringBuilder sb = new StringBuilder("{");
            for (Map.Entry<?, ?> e : ((Map<?, ?>) v).entrySet()) sb.append(sb.length() > 1 ? "," : "").append(Json.canonicalize(e.getKey())).append(':').append(ser(e.getValue()));
            return sb.append('}').toString();
        }
        if (v instanceof List) {
            StringBuilder sb = new StringBuilder("[");
            for (Object x : (List<?>) v) sb.append(sb.length() > 1 ? "," : "").append(ser(x));
            return sb.append(']').toString();
        }
        Double d = IntentJs.num(v);
        if (d != null) return d == Math.rint(d) && Math.abs(d) < 1e17 ? Long.toString(d.longValue()) : d.toString();
        return "<" + v.getClass().getSimpleName() + ":" + v + ">";
    }

    static String reasonWant(String name, Object tsReason) {
        return JAVA_REASON.containsKey(name) ? JAVA_REASON.get(name) : (String) tsReason;
    }

    @Test void oracle() throws Exception {
        List<Object> cs = cases();
        assertTrue(cs.size() > 1900, "only " + cs.size() + " cases");
        List<String> errs = new ArrayList<>();
        int pinned = 0;
        for (Object co : cs) {
            Map<String, Object> c = IntentJs.obj(co);
            String name = (String) c.get("name");
            String kind = (String) c.get("kind");
            String got, want;
            try {
            switch (kind) {
                case "fn":
                    got = ser(VALIDATORS.get((String) c.get("fn")).apply(c.get("arg")));
                    want = ser(c.get("want"));
                    break;
                case "ratio":
                    got = ser(OracleFacts.ratioPpm(IntentJs.lng(c.get("a")), IntentJs.lng(c.get("b"))));
                    want = ser(c.get("want"));
                    break;
                case "flowRule":
                    got = ser(ParamProvenance.flowRuleFor(IntentJs.obj(c.get("rules")), (String) c.get("cls")));
                    want = ser(c.get("want"));
                    break;
                case "flowAllowed":
                    got = ser(ParamProvenance.flowAllowed(IntentJs.obj(c.get("rules")), (String) c.get("cls"), (String) c.get("origin"), (String) c.get("aud")));
                    want = ser(c.get("want"));
                    break;
                case "active":
                    got = ser(OracleFacts.intentWorldActive(c.get("committed"), c.get("policy")));
                    want = ser(c.get("expect"));
                    break;
                case "read": {
                    ParamProvenance.ReadPurposeResult r = ParamProvenance.decideReadPurpose(c.get("input"));
                    got = ser(Map.of("outcome", r.outcome, "minimise", r.minimise, "uncovered", r.uncovered));
                    Map<String, Object> e = IntentJs.obj(c.get("expect"));
                    want = ser(Map.of("outcome", e.get("outcome"), "minimise", e.get("minimise"), "uncovered", e.get("uncovered")));
                    break;
                }
                case "world": {
                    OracleFacts.WorldResult r = OracleFacts.decideIntentWorld(c.get("input"));
                    Map<String, Object> e = IntentJs.obj(c.get("expect"));
                    got = r.ok ? "ok " + ser(r.world) + " " + ser(r.singleSource) + " " + ser(r.reason) : "fail " + ser(r.reason) + " " + ser(r.world) + " " + ser(r.singleSource);
                    want = Boolean.TRUE.equals(e.get("ok")) ? "ok " + ser(e.get("world")) + " " + ser(e.get("single_source")) + " null"
                        : "fail " + ser(reasonWant(name, e.get("reason"))) + " null null";
                    if (JAVA_REASON.containsKey(name)) pinned++;
                    break;
                }
                case "prov": {
                    ParamProvenance.ProvResult r = ParamProvenance.decide(c.get("input"));
                    Map<String, Object> e = IntentJs.obj(c.get("expect"));
                    got = String.join(" | ", r.outcome, ser(r.reason), ser(r.friction), ser(r.labels), ser(r.classes), ser(r.env));
                    want = String.join(" | ", (String) e.get("outcome"), ser(reasonWant(name, e.get("reason"))), ser(e.get("friction")), ser(e.get("labels")), ser(e.get("classes")), ser(e.get("env")));
                    if (JAVA_REASON.containsKey(name)) pinned++;
                    break;
                }
                default:
                    throw new AssertionError("unknown kind " + kind);
            }
            } catch (RuntimeException ex) { errs.add(name + " threw " + ex); continue; }
            if (!got.equals(want)) errs.add(name + "\n    got  " + got + "\n    want " + want);
        }
        assertEquals(JAVA_REASON.size(), pinned, "every pinned divergence names a case");
        assertTrue(errs.isEmpty(), errs.size() + " mismatches:\n" + String.join("\n", errs.subList(0, Math.min(60, errs.size()))));
    }
}
