    /** A grant object whose members cannot be read (a hostile Map): every entry point fails closed instead of throwing. */
    static final class Boom extends LinkedHashMap<String, Object> {
        private static final long serialVersionUID = 1L;
        Boom() { super.put("body", null); super.put("sig", null); }
        @Override public Object get(Object k) { throw new IllegalStateException("boom"); }
    }

    static Map<String, Object> vaultCase() throws Exception {
        for (Map<String, Object> c : K05Oracle.of(MODULE, "vault")) if ("vault/vector allowed-class-to-allowed-sink".equals(c.get("name"))) return c;
        throw new AssertionError("vault/vector allowed-class-to-allowed-sink missing");
    }

    @Test void internalErrorsFailClosed() throws Exception {
        Map<String, Object> c = vaultCase();
        List<?> a = (List<?>) c.get("args"), ra = (List<?>) a.get(1), da = (List<?>) a.get(3);
        Map<String, Object> denied = new LinkedHashMap<>();
        denied.put("decision", "deny"); denied.put("code", "bad_request"); denied.put("view", Map.of()); denied.put("fields", Map.of()); denied.put("labels", List.of()); denied.put("counts", Map.of());
        assertEquals(denied, ReadSide.redactRead(new Boom(), ra.get(0), ra.get(1), ra.get(2), ra.get(3), ra.get(4), ra.get(5), ra.get(6), ra.get(7), ra.get(8), ra.get(9)).toMap());
        Map<String, Object> sinkDenied = new LinkedHashMap<>();
        sinkDenied.put("decision", "deny"); sinkDenied.put("code", "bad_request"); sinkDenied.put("labels", List.of());
        assertEquals(sinkDenied, ReadSide.checkSink(new Boom(), ra.get(0), ra.get(0), ra.get(1), "payments", new ArrayList<>()).toMap());

        // the vault: a store that cannot write fails the read, a store that cannot read fails the detokenization
        ReadVault.VaultStore broken = new ReadVault.VaultStore() {
            @Override public void put(String token, ReadVault.Entry e) { throw new IllegalStateException("disk"); }
            @Override public ReadVault.Entry get(String token) { throw new IllegalStateException("disk"); }
        };
        assertEquals(denied, ReadVault.redactReadWithVault(a.get(0), ra.get(0), ra.get(1), ra.get(2), ra.get(3), ra.get(4), ra.get(5), ra.get(6), ra.get(7), ra.get(8), ra.get(9), broken).toMap());
        Map<String, Object> detDenied = new LinkedHashMap<>();
        detDenied.put("decision", "deny"); detDenied.put("code", "bad_request"); detDenied.put("value", null);
        assertEquals(detDenied, ReadVault.detokenize(a.get(2), da.get(0), da.get(1), da.get(2), "tok_x", broken).toMap());
        assertEquals(detDenied, ReadVault.detokenize(new Boom(), da.get(0), da.get(1), da.get(2), "tok_x", ReadVault.memoryVault()).toMap());

        // an aggregate over an unreadable grant answers bad_request with the EMPTY state (not the caller's)
        Map<String, Object> st = new LinkedHashMap<>();
        st.put("spent_micro", 5L); st.put("queries", 1L); st.put("answered", new LinkedHashMap<String, Object>());
        Map<String, Object> got = ReadVault.aggregateRead(new Boom(), ra.get(0), ra.get(1), "orders.stats", "orders/eu", "analytics", "sum", List.of(1L, 2L, 3L), "a-per-read-secret-salt", "seeded", st).toMap();
        assertEquals("bad_request", got.get("code"));
        assertEquals(ReadVault.State.empty().toMap(), got.get("state"));
        assertEquals(0L, got.get("charged_micro"));
    }

    // ---- the sampler over scripted streams (the rejection and give-up paths no SHA-256 stream reaches) ----

    /** A stream that hands out the given values in order, then repeats the last, counting reads. */
    static final class Script implements java.util.function.LongSupplier {
        final long[] vs;
        int reads;
        Script(long... vs) { this.vs = vs; }
        @Override public long getAsLong() { return vs[Math.min(reads++, vs.length - 1)]; }
    }

    @Test void uniformRejectsAtTheLimit() {
        long top = (1L << 48) - 1; // 2^48 = 1 (mod 3): the limit for n = 3 is 2^48 - 1, so 2^48 - 1 is rejected
        Script s = new Script(top, top - 1);
        assertEquals((top - 1) % 3, ReadVault.fromStream(s).uniform(3));
        assertEquals(2, s.reads);
        Script p = new Script(top);
        assertEquals((1L << 47) - 1, ReadVault.fromStream(p).uniform(1L << 47)); // 2^47 divides 2^48: nothing is rejected
        assertEquals(1, p.reads);
        Script one = new Script(top, 5);
        assertEquals(0, ReadVault.fromStream(one).uniform(1));
        assertEquals(1, one.reads);
        Script lim = new Script(top - 1);
        assertEquals((top - 1) % 7, ReadVault.fromStream(lim).uniform(7)); // 2^48 = 1 (mod 7): limit 2^48 - 1
        assertEquals(1, lim.reads);
        Script rej = new Script(top - 3, top - 4); // 2^48 = 4 (mod 6): limit 2^48 - 4 = top - 3, which is rejected
        assertEquals((top - 4) % 6, ReadVault.fromStream(rej).uniform(6));
        assertEquals(2, rej.reads);
    }

    @Test void uniformGivesUpAfterTheStepBound() {
        Script s = new Script((1L << 48) - 1);
        IllegalArgumentException e = assertThrows(IllegalArgumentException.class, () -> ReadVault.fromStream(s).uniform(3));
        assertEquals("uniform: no draw", e.getMessage());
        assertEquals(100_000, s.reads);
        for (long bad : new long[] {0, -1, (1L << 47) + 1}) {
            Script t = new Script(0);
            assertEquals("uniform: bad bound", assertThrows(IllegalArgumentException.class, () -> ReadVault.fromStream(t).uniform(bad)).getMessage());
            assertEquals(0, t.reads);
        }
    }

    /** Draws answering f(n) for a bound n, counting calls (values outside [0, n) are allowed: the sampler must not assume them). */
    static final class Fixed implements ReadVault.Draws {
        final java.util.function.LongUnaryOperator f;
        long calls;
        Fixed(java.util.function.LongUnaryOperator f) { this.f = f; }
        @Override public long uniform(long n) { calls++; return f.applyAsLong(n); }
    }

    @Test void laplaceGiveUpPaths() {
        // every Bernoulli succeeds: the inner exp(-1) trial never stops
        Fixed zero = new Fixed(n -> 0);
        assertEquals("bernoulli: no termination", assertThrows(IllegalArgumentException.class, () -> ReadVault.discreteLaplace(zero, 1, 1)).getMessage());
        assertEquals(100_002, zero.calls);
        // every exp(-1) trial succeeds at once: the geometric count never stops
        Fixed high = new Fixed(n -> n);
        assertEquals("laplace: no termination", assertThrows(IllegalArgumentException.class, () -> ReadVault.discreteLaplace(high, 1, 3)).getMessage());
        assertEquals(100_003, high.calls);
        // every sample is a negative zero, which is rejected and redrawn
        Fixed negZero = new Fixed(n -> n == 2 ? 1 : 0);
        assertEquals("laplace: no sample", assertThrows(IllegalArgumentException.class, () -> ReadVault.discreteLaplace(negZero, 1, 3)).getMessage());
        assertEquals(500_000, negZero.calls);
    }

    @Test void laplaceComposesItsDraws() {
        // u = 2 of t = 5; exp(-2/5) accepted (its first trial fails); v = 1 (one exp(-1) success, then a failure at k = 2); sign negative
        long[] script = {2, 9, 9, 0, 1, 1};
        int[] at = {0};
        ReadVault.Draws d = n -> script[at[0]++];
        assertEquals(-((2 + 5) / 3), ReadVault.discreteLaplace(d, 3, 5));
        assertEquals(6, at[0]);
        long[] pos = {4, 9, 0, 9, 0};
        int[] at2 = {0};
        ReadVault.Draws d2 = n -> pos[at2[0]++];
        assertEquals(4 / 2, ReadVault.discreteLaplace(d2, 2, 5));
        assertEquals(5, at2[0]);
    }

    @Test void secureDrawsSeedWithThirtyTwoFreshBytes() {
        java.security.SecureRandom fixed = new java.security.SecureRandom() {
            private static final long serialVersionUID = 1L;
            @Override public void nextBytes(byte[] b) { for (int i = 0; i < b.length; i++) b[i] = (byte) (i + 1); }
        };
        byte[] want = new byte[32];
        for (int i = 0; i < 32; i++) want[i] = (byte) (i + 1);
        ReadVault.Draws a = ReadVault.secureDraws(fixed), b = ReadVault.seededDraws(Pca.b64(want));
        for (int i = 0; i < 12; i++) assertEquals(b.uniform(1L << 47), a.uniform(1L << 47));
    }

    /** 'secure' noise is not the seeded stream: 16 fresh answers are not all the seeded answer (each matches it with p ~ 1/400). */
    @Test void secureNoiseIsNotTheSeededNoise() throws Exception {
        Map<String, Object> base = null;
        for (Map<String, Object> c : K05Oracle.of(MODULE, "aggregateRead")) if ("aggregateRead/base".equals(c.get("name"))) base = c;
        assertTrue(base != null);
        List<?> a = (List<?>) base.get("args");
        Object seeded = m(base.get("out")).get("value");
        assertTrue(seeded != null);
        boolean differs = false;
        for (int i = 0; i < 16 && !differs; i++) {
            ReadVault.Aggregate r = ReadVault.aggregateRead(a.get(0), a.get(1), a.get(2), a.get(3), a.get(4), a.get(5), a.get(6), a.get(7), a.get(8), "secure", a.get(10));
            assertEquals("allow", r.decision);
            differs = !IntentJs.jsonEquals(seeded, r.value);
        }
        assertTrue(differs, "16 'secure' answers all equal the seeded one");
    }

    /** A store may hold an entry that expires before its grant (the digest binds the grant, not the entry): the entry's expiry gates. */
    @Test void detokenizeHonoursTheEntryExpiry() throws Exception {
        Map<String, Object> c = vaultCase();
        List<?> a = (List<?>) c.get("args"), da = (List<?>) a.get(3);
        String digest = ReadSide.readGrantDigest(m(a.get(2)).get("body"));
        long now = Json.asLong(da.get(1));
        for (long exp : new long[] {now - 1, now, now + 1}) {
            ReadVault.VaultStore s = ReadVault.memoryVault();
            s.put("tok_x", new ReadVault.Entry("ref", "c_77", digest, exp));
            Map<String, Object> got = ReadVault.detokenize(a.get(2), da.get(0), da.get(1), da.get(2), "tok_x", s).toMap();
            Map<String, Object> want = new LinkedHashMap<>();
            want.put("decision", exp > now ? "allow" : "deny"); want.put("code", exp > now ? null : "expired"); want.put("value", exp > now ? "c_77" : null);
            assertEquals(want, got, "exp " + (exp - now));
        }
    }

    /** The vault forgets nothing it was told and knows nothing else; a null token is unknown. */
    @Test void memoryVault() {
        ReadVault.VaultStore s = ReadVault.memoryVault();
        ReadVault.Entry e = new ReadVault.Entry("ref", "v", "g", 5);
        s.put("t", e);
        assertTrue(s.get("t") == e);
        assertTrue(s.get("u") == null);
        assertTrue(s.get(null) == null);
    }
