    static final String MODULE = "k05-readside";

    @SuppressWarnings("unchecked") static Map<String, Object> m(Object o) { return (Map<String, Object>) o; }
    @SuppressWarnings("unchecked") static List<Object> l(Object o) { return (List<Object>) o; }

    interface Fn { Object apply(List<?> a) throws Exception; }

    static void each(String fn, Fn f) throws Exception {
        List<Map<String, Object>> cases = K05Oracle.of(MODULE, fn);
        assertFalse(cases.isEmpty(), "no oracle cases for " + fn);
        List<String> bad = new ArrayList<>();
        for (Map<String, Object> c : cases) {
            Object want = c.get("out");
            List<?> a = (List<?>) c.get("args");
            Object got = null;
            Throwable err = null;
            try { got = f.apply(a); } catch (Throwable t) { err = t; }
            if (want instanceof Map && m(want).containsKey("$throws")) {
                if (err == null) bad.add(c.get("name") + "\n  want: throw " + want + "\n  got:  " + got);
            } else if (err != null) {
                bad.add(c.get("name") + "\n  want: " + want + "\n  got:  THROWS " + err);
            } else if (!IntentJs.jsonEquals(want, got)) {
                bad.add(c.get("name") + "\n  want: " + want + "\n  got:  " + got);
            }
        }
        assertTrue(bad.isEmpty(), bad.size() + " of " + cases.size() + " divergent case(s):\n" + String.join("\n", bad.subList(0, Math.min(bad.size(), 40))));
    }

