package net.atlasauth.pca;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;

/**
 * 0.5 mutation kills for {@link Lease} and {@link BreakGlass}: a differential test against the TS reference (the shared k05 grants
 * oracle, test-data/k05-grants.json.gz, generated by tools/pca-audit/k05-oracles/grants-oracle.mts). Record shapes run unsigned and
 * re-signed (so the shape check is not masked by the signature); registry walks replay every step on a fresh registry and compare
 * each step's whole result. Plus the store-failure paths the reference cannot reach in memory.
 */
public class K05GrantsDiffTest {
    static final String MODULE = "k05-grants";

    @SuppressWarnings("unchecked") static Map<String, Object> m(Object o) { return (Map<String, Object>) o; }
    @SuppressWarnings("unchecked") static List<Object> l(Object o) { return (List<Object>) o; }
    static List<String> strs(Object o) { List<String> out = new ArrayList<>(); for (Object x : l(o)) out.add((String) x); return out; }
    static Map<String, Object> map(Object... kv) {
        Map<String, Object> out = new LinkedHashMap<>();
        for (int i = 0; i < kv.length; i += 2) out.put((String) kv[i], kv[i + 1]);
        return out;
    }

    interface Fn { Object apply(List<?> a) throws Exception; }

    static void each(String fn, Fn f) throws Exception {
        List<Map<String, Object>> cases = K05Oracle.of(MODULE, fn);
        assertFalse(cases.isEmpty(), "no oracle cases for " + fn);
        List<String> bad = new ArrayList<>();
        for (Map<String, Object> c : cases) {
            Object want = c.get("out");
            Object got = null;
            Throwable err = null;
            try { got = f.apply((List<?>) c.get("args")); } catch (Throwable t) { err = t; }
            if (want instanceof Map && m(want).containsKey("$throws")) {
                if (err == null) bad.add(c.get("name") + "\n  want: throw " + want + "\n  got:  " + got);
            } else if (err != null) {
                bad.add(c.get("name") + "\n  want: " + want + "\n  got:  THROWS " + err);
            } else if (!IntentJs.jsonEquals(want, got)) {
                bad.add(c.get("name") + "\n  want: " + want + "\n  got:  " + got);
            }
        }
        assertTrue(bad.isEmpty(), bad.size() + " of " + cases.size() + " divergent case(s):\n" + String.join("\n", bad.subList(0, Math.min(bad.size(), 40))));
    }

    static Object arg0(String fn, String name) throws Exception {
        for (Map<String, Object> c : K05Oracle.of(MODULE, fn)) if ((fn + "/" + name).equals(c.get("name"))) return l(c.get("args")).get(0);
        throw new AssertionError("no oracle case " + fn + "/" + name);
    }

    static Lease.Policy policy(Object po) {
        Map<String, Object> p = m(po);
        Lease.Policy out = new Lease.Policy(p.get("authorities") == null ? null : strs(p.get("authorities")));
        if (p.get("minApprovals") != null) out.minApprovals = Json.asLong(p.get("minApprovals"));
        if (p.get("eligibleApprovers") != null) out.eligibleApprovers = strs(p.get("eligibleApprovers"));
        if (p.get("freshJustification") != null) out.freshJustification = (Boolean) p.get("freshJustification");
        if (p.get("maxTtlCeiling") != null) out.maxTtlCeiling = Json.asLong(p.get("maxTtlCeiling"));
        return out;
    }

    static Map<String, Object> accept(Lease.Accept a) {
        if (a.code == null) return map("ok", true, "replaced", a.replaced, "seq", a.seq);
        if (a.replaced || a.seq != 0) throw new AssertionError("a refusal carries replaced=false, seq=0");
        return map("ok", false, "code", a.code);
    }
    static Map<String, Object> revoke(Lease.Revoke r) {
        if (r.code == null) return map("ok", true, "revoked", (long) r.revoked);
        if (r.revoked != 0) throw new AssertionError("a refusal carries revoked=0");
        return map("ok", false, "code", r.code);
    }
    static Map<String, Object> decision(Lease.Decision d) {
        Map<String, Object> out = map("decision", d.decision);
        if (d.code != null) out.put("code", d.code);
        if (d.leaseId != null) out.put("lease_id", d.leaseId);
        if (d.expiresAt != null) out.put("expires_at", d.expiresAt);
        return out;
    }

    @Test void verifyLease() throws Exception { each("verifyLease", a -> Lease.verify(a.get(0))); }
    @Test void verifyLeaseRevocation() throws Exception { each("verifyLeaseRevocation", a -> Lease.verifyRevocation(a.get(0))); }
    @Test void verifyBreakGlass() throws Exception { each("verifyBreakGlass", a -> BreakGlass.verify(a.get(0))); }
    @Test void verifyBreakGlassReview() throws Exception { each("verifyBreakGlassReview", a -> BreakGlass.verifyReview(a.get(0))); }

    @Test void sodError() throws Exception { each("sodError", a -> Lease.sodError(m(a.get(0)), policy(a.get(1)), strs(a.get(2)))); }

    @Test void leaseWalk() throws Exception {
        each("leaseWalk", a -> {
            Lease.Registry reg = new Lease.Registry(policy(a.get(0)));
            List<Object> out = new ArrayList<>();
            for (Object sx : l(a.get(1))) {
                Map<String, Object> s = m(sx);
                Object op = s.get("op");
                if ("accept".equals(op)) out.add(accept(reg.accept(s.get("rec"), s.get("chain") == null ? List.of() : strs(s.get("chain")))));
                else if ("revoke".equals(op)) out.add(revoke(reg.revoke(s.get("rec"))));
                else out.add(decision(reg.check(s.get("rec"), s.get("now"))));
            }
            return out;
        });
    }

    @Test void bgWalk() throws Exception {
        each("bgWalk", a -> {
            Map<String, Object> p = m(a.get(0));
            BreakGlass.Registry reg = new BreakGlass.Registry(strs(p.get("authorities")), strs(p.get("reviewers")));
            List<Object> out = new ArrayList<>();
            for (Object sx : l(a.get(1))) {
                Map<String, Object> s = m(sx);
                Object op = s.get("op");
                if ("accept".equals(op)) out.add(reg.accept(s.get("rec"), s.get("now")));
                else if ("use".equals(op)) out.add(reg.use(s.get("id"), s.get("holder"), s.get("action_digest"), s.get("now"), s.get("notified")));
                else if ("review".equals(op)) out.add(reg.review(s.get("rec"), s.get("holder"), s.get("now")));
                else out.add(reg.frozen(s.get("holder"), s.get("now")));
            }
            return out;
        });
    }

    /** A record whose get(armed) throws: a store that fails after the record was taken. */
    static final class Trap extends LinkedHashMap<String, Object> {
        String armed;
        Trap(Map<String, Object> m) { super(m); }
        @Override public Object get(Object k) {
            if (k != null && k.equals(armed)) throw new IllegalStateException("store failed reading " + k);
            return super.get(k);
        }
    }

    static final long T0 = 1_800_000_000_000L;

    // lease.ts:219 and :245, lease-store-conformance.ts section 8
    @Test void maxTtlCeiling() throws Exception {
        Map<String, Object> lease = m(arg0("verifyLease", "base"));
        long ttl = Json.asLong(lease.get("max_ttl"));
        List<String> auth = List.of((String) lease.get("authority"));
        for (long[] row : new long[][] {{ttl - 1, 1}, {ttl, 0}, {ttl + 1, 0}}) {
            Lease.Policy p = new Lease.Policy(auth);
            p.maxTtlCeiling = row[0];
            assertEquals(row[1] == 1 ? "ttl_ceiling" : null, new Lease.Registry(p).accept(new LinkedHashMap<>(lease), List.of()).code, "ceiling " + row[0]);
        }
        assertNull(new Lease.Registry(new Lease.Policy(auth)).accept(new LinkedHashMap<>(lease), List.of()).code, "no ceiling");
        Lease.Policy sane = new Lease.Policy(auth);
        sane.maxTtlCeiling = 1L;
        assertEquals("ttl_ceiling", new Lease.Registry(sane).accept(new LinkedHashMap<>(lease), List.of()).code, "the smallest ceiling is legal");
        sane.maxTtlCeiling = 9007199254740991L;
        assertNull(new Lease.Registry(sane).accept(new LinkedHashMap<>(lease), List.of()).code, "the largest ceiling is legal");
        for (long bad : new long[] {0, -1, 9007199254740992L}) {
            Lease.Policy p = new Lease.Policy(auth);
            p.maxTtlCeiling = bad;
            IllegalArgumentException e = assertThrows(IllegalArgumentException.class, () -> new Lease.Registry(p));
            assertEquals("LeaseRegistry: maxTtlCeiling must be a positive integer", e.getMessage());
        }
    }

    @Test void leaseStoreFailuresFailClosed() throws Exception {
        Map<String, Object> lease = m(arg0("verifyLease", "base")), rev = m(arg0("verifyLeaseRevocation", "base"));
        assertTrue(Lease.verify(lease));
        assertTrue(Lease.verifyRevocation(rev));
        // a policy without its authority list: the registry cannot decide, so it refuses as unreachable
        Lease.Registry broken = new Lease.Registry(new Lease.Policy(null));
        Lease.Accept a = broken.accept(lease, List.of());
        assertEquals("store_unreachable", a.code);
        assertFalse(a.replaced);
        assertEquals(0L, a.seq);
        Lease.Revoke r = broken.revoke(rev);
        assertEquals("store_unreachable", r.code);
        assertEquals(0, r.revoked);
        // the stored record fails on read during a check
        Lease.Registry reg = new Lease.Registry(new Lease.Policy(List.of((String) lease.get("authority"))));
        Trap stored = new Trap(lease);
        Lease.Accept ok = reg.accept(stored, List.of());
        assertNull(ok.code);
        assertTrue(ok.replaced);
        assertEquals(1L, ok.seq);
        Lease.Decision live = reg.check(new LinkedHashMap<>(lease), T0 + 100);
        assertEquals("allow", live.decision);
        assertEquals(T0 + 600, (long) live.expiresAt);
        stored.armed = "sig";
        Lease.Decision d = reg.check(new LinkedHashMap<>(lease), T0 + 100);
        assertEquals("deny", d.decision);
        assertEquals("store_unreachable", d.code);
        assertEquals("L1", d.leaseId);
        assertNull(d.expiresAt);
    }

    @Test void breakGlassStoreFailuresFailClosed() throws Exception {
        Map<String, Object> bg = m(arg0("verifyBreakGlass", "base")), rv = m(arg0("verifyBreakGlassReview", "base"));
        assertTrue(BreakGlass.verify(bg));
        assertTrue(BreakGlass.verifyReview(rv));
        String holder = (String) bg.get("holder");
        List<String> auth = List.of((String) bg.get("authority")), revs = List.of((String) rv.get("reviewer"));
        BreakGlass.Registry broken = new BreakGlass.Registry(null, null);
        assertEquals(map("ok", false, "code", "store_unreachable"), broken.accept(bg, T0));
        assertEquals(map("ok", false, "code", "store_unreachable"), broken.review(rv, holder, T0 + 20));
        // the stored grant fails on read during a use
        BreakGlass.Registry reg = new BreakGlass.Registry(auth, revs);
        Trap stored = new Trap(bg);
        assertEquals(map("ok", true, "replaced", true), reg.accept(stored, T0));
        stored.armed = "max_uses";
        assertEquals(map("decision", "deny", "code", "store_unreachable", "id", "bg1"), reg.use("bg1", holder, "act", T0 + 10, true));
        // ... and during a freeze check (a store failure reads as frozen)
        BreakGlass.Registry reg2 = new BreakGlass.Registry(auth, revs);
        Trap stored2 = new Trap(bg);
        assertEquals(map("ok", true, "replaced", true), reg2.accept(stored2, T0));
        assertEquals(map("decision", "allow", "id", "bg1", "use", 1L, "remaining", 1L, "review_due", T0 + 510), reg2.use("bg1", holder, "act", T0 + 10, true));
        assertFalse(reg2.frozen(holder, T0 + 10));
        stored2.armed = "review_within";
        assertTrue(reg2.frozen(holder, T0 + 10));
    }
}
