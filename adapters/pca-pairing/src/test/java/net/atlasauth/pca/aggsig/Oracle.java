package net.atlasauth.pca.aggsig;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.zip.GZIPInputStream;
import net.atlasauth.pca.Json;
import net.atlasauth.pca.Keys;

/**
 * Replays a TypeScript-reference oracle (test-data/&lt;module&gt;.json.gz: a header, then one {fn, name, args, out} case per line).
 * Bytes are {"$bytes": b64url}; {"$throws": ...} means the native must throw. Results compare as canonical JSON.
 */
public final class Oracle {
    private Oracle() {}

    public interface Fn { Object apply(List<?> args) throws Exception; }

    @SuppressWarnings("unchecked")
    public static List<Map<String, Object>> of(String module, String fn) throws Exception {
        List<Map<String, Object>> out = new ArrayList<>();
        String head = "{\"fn\":" + Json.canonicalize(fn) + ",";
        readInto(out, Path.of("test-data/" + module + ".json.gz"), head);
        Path gen = genPath(module);
        if (module.equals("ref-abe") && Files.exists(gen)) readInto(out, gen, head);
        assertFalse(out.isEmpty(), "no oracle cases for " + module + "/" + fn);
        return out;
    }

    /** ref-abe-gen.json.gz is generated by CI (never committed): next to the main corpus, PCA_SECRET_CORPUS_DIR overrides the directory. */
    public static Path genPath(String module) {
        String env = System.getenv("PCA_SECRET_CORPUS_DIR");
        return (env != null && !env.isEmpty() ? Path.of(env) : Path.of("test-data").toAbsolutePath()).resolve(module + "-gen.json.gz");
    }

    @SuppressWarnings("unchecked")
    private static void readInto(List<Map<String, Object>> out, Path file, String head) throws Exception {
        try (BufferedReader in = new BufferedReader(new InputStreamReader(
                new GZIPInputStream(Files.newInputStream(file)), StandardCharsets.UTF_8))) {
            for (String line; (line = in.readLine()) != null; ) {
                if (!line.startsWith(head)) continue;
                if (line.endsWith(",")) line = line.substring(0, line.length() - 1);
                out.add((Map<String, Object>) unbbs(Json.parseLenient(line)));
            }
        }
    }

    /** The BBS corpus carries no signing keys: {"$bbssk": n} stands for KeyGen(32 bytes of n, empty key info), as 64 lowercase hex digits. */
    @SuppressWarnings("unchecked")
    private static Object unbbs(Object v) {
        if (v instanceof Map) {
            Map<String, Object> m = (Map<String, Object>) v;
            if (m.size() == 1 && (m.get("$bbssk") instanceof Number || m.get("$bbssk") instanceof Json.Num)) {
                byte[] ikm = new byte[32];
                java.util.Arrays.fill(ikm, (byte) Integer.parseInt(m.get("$bbssk").toString()));
                return String.format("%064x", net.atlasauth.pca.bbs.Bbs.keyGen(ikm));
            }
            for (Map.Entry<String, Object> e : m.entrySet()) e.setValue(unbbs(e.getValue()));
        } else if (v instanceof List) {
            List<Object> l = (List<Object>) v;
            for (int i = 0; i < l.size(); i++) l.set(i, unbbs(l.get(i)));
        }
        return v;
    }

    @SuppressWarnings("unchecked")
    public static byte[] bytes(Object o) {
        if (o instanceof Map && ((Map<String, Object>) o).get("$bytes") instanceof String) return Keys.unb64u((String) ((Map<String, Object>) o).get("$bytes"));
        throw new IllegalArgumentException("not a $bytes value: " + o);
    }

    public static List<byte[]> bytesList(Object o) {
        List<byte[]> out = new ArrayList<>();
        for (Object x : (List<?>) o) out.add(bytes(x));
        return out;
    }

    @SuppressWarnings("unchecked")
    public static Object toJson(Object v) {
        if (v instanceof byte[]) { Map<String, Object> m = new LinkedHashMap<>(); m.put("$bytes", Keys.b64u((byte[]) v)); return m; }
        if (v instanceof Map) {
            Map<String, Object> out = new LinkedHashMap<>();
            for (Map.Entry<String, Object> e : ((Map<String, Object>) v).entrySet()) out.put(e.getKey(), toJson(e.getValue()));
            return out;
        }
        if (v instanceof List) { List<Object> out = new ArrayList<>(); for (Object x : (List<Object>) v) out.add(toJson(x)); return out; }
        return v;
    }

    @SuppressWarnings("unchecked")
    public static void each(String module, String fn, Fn f) throws Exception {
        List<String> bad = new ArrayList<>();
        for (Map<String, Object> c : of(module, fn)) {
            Object want = c.get("out");
            boolean wantThrow = want instanceof Map && ((Map<String, Object>) want).containsKey("$throws");
            Object got = null;
            Throwable err = null;
            try { got = f.apply((List<?>) c.get("args")); } catch (Throwable t) { err = t; }
            if (wantThrow) {
                if (err == null) bad.add(c.get("name") + ": want a throw, got " + Json.canonicalize(toJson(got)));
            } else if (err != null) {
                bad.add(c.get("name") + ": unexpected " + err);
            } else {
                String a = Json.canonicalize(want);
                String b = Json.canonicalize(toJson(got));
                if (!a.equals(b)) bad.add(c.get("name") + "\n  want " + a + "\n  got  " + b);
            }
        }
        assertTrue(bad.isEmpty(), bad.size() + " divergent case(s) of " + fn + ":\n" + String.join("\n", bad.subList(0, Math.min(bad.size(), 30))));
    }
}
